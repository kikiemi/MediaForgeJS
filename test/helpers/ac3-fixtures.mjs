// AC-3 fixtures produced by ffmpeg 6.1.1 (its ac3 encoder) from the deterministic signal
// codecSignal() of ./vorbis-fixtures.mjs written as a 16-bit WAV at sampleRate:
//   ffmpeg -i signal.wav <arguments> <name>.<container>
// and E-AC-3 ones (codec 'ec-3', its eac3 encoder) the same way. The 7.1 E-AC-3 stream joins each
// frame of a 5.1 encode (the independent substream) and the matching frame of a stereo encode of
// codecSignal's channels 6 and 7, turned into a dependent substream with a channel map of Lrs/Rrs:
// its type and channel map set, the fields only independent frames carry removed, padded to whole
// words.
// Each entry carries referenceFrames frames of ffmpeg's own float decode (ffmpeg -i <name> -f
// f32le -) from presentation frame referenceStart (for the 7.1 stream, the decodes of its two
// encodes in WAVE order: FL FR FC LFE from the 5.1, BL BR from the stereo, SL SR from the 5.1), and
// `frames`, the frame count of the presentation: that decode's, except where an MP4 edit list ends
// the presentation inside the last frame, which the ffmpeg command line decodes whole.
// The decodes differ by the dither of the zero-bit mantissas (A/52 7.3.4), whose generators
// differ, so they agree to the dither's level rather than exactly.

function base64Bytes(text) {
    const binary = atob(text);
    const bytes = new Uint8Array(binary.length);
    for (let index = 0; index < binary.length; index++) bytes[index] = binary.charCodeAt(index);
    return bytes;
}

/** Interleaved float32 little-endian samples. */
function base64Float32(text) {
    const bytes = base64Bytes(text);
    return new Float32Array(bytes.buffer, 0, bytes.length >> 2);
}

